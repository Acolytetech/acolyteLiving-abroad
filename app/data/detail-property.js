export function classifyAmenities(apiAmenities) {
  const CATEGORY_MAP = {
    Safety: [
      "CCTV",
      "24 hours security",
      "Fire system",
      "Controlled Access",
      "Video Surveillance",
      "Security Guard",
      "Doorman",
      "Pest Control",
      "Elevator Access Control",
    ],

    "Property Services": [
      "Package Room",
      "Reception",
      "Delivery Alert System",
      "Mailroom",
      "Business Center",
      "Conference Room",
      "Free Printing",
    ],

    "Shared Community": [
      "Laundry Room",
      "Wi-Fi",
      "Elevator",
      "Lounge",
      "Bike Storage",
      "Study Room",
      "Communal Kitchen",
      "Dining Hall",
      "Trash Room",
    ],

    "Fitness & Recreation": [
      "Gym",
      "Game Room",
      "Cinema room",
      "Pool Table",
      "Social events",
      "Outdoor Lounge",
      "Courtyard",
      "Terrace",
      "Rooftop",
    ],
  };

  // Initialize result structure
  const result = Object.keys(CATEGORY_MAP).map((category) => ({
    category,
    amenities: [],
  }));

  // Classify amenities
  apiAmenities.forEach(({ name }) => {
    for (const category in CATEGORY_MAP) {
      if (CATEGORY_MAP[category].includes(name)) {
        const target = result.find((item) => item.category === category);

        // Avoid duplicates
        if (!target.amenities.includes(name)) {
          target.amenities.push(name);
        }
        break;
      }
    }
  });

  // Remove empty categories
  return result.filter((item) => item.amenities.length > 0);
}
